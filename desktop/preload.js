const { contextBridge, ipcRenderer } = require('electron');

const send = (ch, ...a) => ipcRenderer.send(ch, ...a);
const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('lumen', {
  platform: process.platform,
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onFocusUrl: (cb) => ipcRenderer.on('focus-url', () => cb()),
  onOpenPanel: (cb) => ipcRenderer.on('open-panel', (_e, name) => cb(name)),
  onFindOpen: (cb) => ipcRenderer.on('open-find', () => cb()),
  onPwOffer: (cb) => ipcRenderer.on('pw:offer', (_e, row) => cb(row)),
  onPerm: (cb) => ipcRenderer.on('perm:ask', (_e, row) => cb(row)),
  onFindResult: (cb) => ipcRenderer.on('find-result', (_e, row) => cb(row)),
  ready: () => send('ui:ready'),
  newTab: () => send('tab:new'),
  activate: (id) => send('tab:activate', id),
  close: (id) => send('tab:close', id),
  sleep: (id) => send('tab:sleep', id),
  go: (text) => send('nav:go', text),
  nav: (action) => send('nav:action', action),
  panel: (width) => send('panel:width', width),
  chrome: (top, side) => send('chrome:bounds', top, side),
  zoomSet: (percent) => send('zoom:set', percent),
  find: (text, opts) => send('find:query', text, opts || {}),
  perm: (id, allow) => send('perm:reply', id, allow),
  setSettings: (patch) => call('settings:set', patch),
  wallSet: (dataUrl) => call('wall:set', dataUrl),
  wallGet: () => call('wall:get'),
  wallClear: () => send('wall:clear'),
  bookmarks: () => call('bm:list'),
  toggleBookmark: () => call('bm:toggle'),
  removeBookmark: (url) => send('bm:remove', url),
  history: () => call('hist:list'),
  clearHistory: () => send('hist:clear'),
  passwords: () => call('pw:list'),
  pwSave: (row) => call('pw:save', row),
  pwReveal: (id) => call('pw:reveal', id),
  pwRemove: (id) => send('pw:remove', id),
  pwNever: (origin) => send('pw:never', origin),
  pwNeverClear: () => send('pw:never-clear'),
  pwFill: (id) => call('pw:fill', id),
  pwFillBest: () => call('pw:fill-best'),
  dlCancel: (id) => send('dl:cancel', id),
  dlPause: (id) => send('dl:pause', id),
  dlOpen: (id) => send('dl:open', id),
  dlShow: (id) => send('dl:show', id),
  dlForget: (id) => send('dl:forget', id),
  dlClear: () => send('dl:clear'),
  clearData: () => call('data:clear'),
  metrics: () => call('tabs:metrics'),
  blocked: () => call('adblock:stats'),
});
